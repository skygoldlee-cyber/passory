def replace_first_cell(text: str, old: str, new: str, label: str):
    """표 데이터행의 첫 셀(원료명)만 교체. old가 정확히 1곳 이상 있어야 함."""
    needle = '| ' + old + ' |'
    n = text.count(needle)
    if n == 0:
        report['rename_miss'].append((label, old))
        return text
    report['rename_ok'] += 1
    return text.replace(needle, '| ' + new + ' |')


def replace_row_text(text: str, old: str, new: str, label: str):
    """행 내 임의 텍스트 교체(설명 셀 포함). 없으면 기록."""
    if old not in text:
        report['rename_miss'].append((label, old))
        return text
    report['rename_ok'] += 1
    return text.replace(old, new)


def insert_after(text: str, anchor_line: str, new_lines: list, label: str):
    """anchor_line 바로 다음에 new_lines 삽입."""
    if anchor_line not in text:
        report['rename_miss'].append((label, 'ANCHOR:' + anchor_line[:60]))
        return text
    report['add'] += len(new_lines)
    return text.replace(anchor_line, anchor_line + '\n' + '\n'.join(new_lines), 1)


